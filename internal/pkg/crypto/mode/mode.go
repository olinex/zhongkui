// Package mode 提供对称加密算法的实现，支持多种加密模式。
// 当前实现了 AES-GCM（Galois/Counter Mode）认证加密模式。
//
// AES-GCM 是一种认证加密模式，同时提供数据机密性和完整性保护。
// 它使用 nonce（一次性随机数）和可选的附加认证数据（AAD）来确保：
//   - 数据机密性：明文被加密为密文
//   - 数据完整性：密文被篡改时解密会失败
//   - 认证性：可选的 AAD 数据也被认证但不加密
//
// 所有实现都遵循 Mode 接口，提供统一的 Encrypt/Decrypt API。
package mode

// Mode 定义对称加密算法的统一接口。
// 所有加密模式实现都必须支持加密和解密操作。
//
// 实现要求：
//   - Encrypt 必须使用安全的随机 nonce
//   - Decrypt 必须验证认证标签，失败时返回错误
//   - 相同的明文和密钥，不同次加密应产生不同的密文
type Mode interface {
	// Encrypt 对明文进行加密，返回密文。
	// 密文格式由具体实现决定，通常包含 nonce 和认证标签。
	//
	// 参数：
	//   - p: 待加密的明文字节数组，可以为空
	//
	// 返回值：
	//   - []byte: 加密后的密文，包含 nonce 和认证信息
	//   - error: 加密过程中发生错误时返回非 nil 错误
	Encrypt(p []byte) ([]byte, error)

	// Decrypt 对密文进行解密，返回明文。
	// 会自动验证认证标签，如果密文被篡改或密钥不匹配则返回错误。
	//
	// 参数：
	//   - p: 待解密的密文字节数组，格式必须与 Encrypt 的输出一致
	//
	// 返回值：
	//   - []byte: 解密后的明文
	//   - error: 解密失败（认证错误、数据损坏等）时返回非 nil 错误
	Decrypt(p []byte) ([]byte, error)
}
