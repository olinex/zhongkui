	namespace,
	capture,
	version,
	session_id,
	top_proto,
	proto,
	level,
	seq,
	timestamp
)
PARTITION BY toStartOfHour(created_at)
TTL toDateTime(created_at) + INTERVAL 180 DAY DELETE;

