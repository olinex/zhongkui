CREATE TABLE IF NOT EXISTS network_stacks (
	namespace LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the namespace the frame belongs to',
	capture LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the name of the capturer',
	version LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the version of the capturer',
	session_id UUID CODEC(ZSTD(3)) COMMENT 'the session id of the frame',
	trace_id UUID CODEC(ZSTD(3)) COMMENT 'the trace id linking the frame to its related records',
	timestamp DateTime64(6, 'UTC') CODEC(DoubleDelta, ZSTD(3)) COMMENT 'the capture timestamp of the frame',
	created_at DateTime64(6, 'UTC') CODEC(DoubleDelta, ZSTD(3)) COMMENT 'the time the record is created',
	cli_2_srv Bool COMMENT 'whether the frame is in the client to server direction',
	top_proto UInt64 CODEC(ZSTD(3)) COMMENT 'the top layer protocol of the packet',
	proto UInt64 CODEC(ZSTD(3)) COMMENT 'the protocol of the current layer',
	seq UInt32 CODEC(ZSTD(3)) COMMENT 'the sequence of the frame keeping its order in the layer stack',
	level UInt8 CODEC(ZSTD(3)) COMMENT 'the protocol level of the layer (link, network, transport, application)',
	headers String CODEC(ZSTD(3)) COMMENT 'the JSON serialized header info of the layer'
) ENGINE = MergeTree()
