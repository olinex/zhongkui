	childs_dispersion_n String CODEC(ZSTD(3)) COMMENT 'the count of the children dispersion statistics of the node',
	childs_dispersion_line_sum String CODEC(ZSTD(3)) COMMENT 'the line sum of the children dispersion statistics of the node',
	childs_dispersion_square_sum String CODEC(ZSTD(3)) COMMENT 'the square sum of the children dispersion statistics of the node',
	childs_concentration_n String CODEC(ZSTD(3)) COMMENT 'the count of the children concentration statistics of the node',
	childs_concentration_line_sum String CODEC(ZSTD(3)) COMMENT 'the line sum of the children concentration statistics of the node',
	childs_concentration_square_sum String CODEC(ZSTD(3)) COMMENT 'the square sum of the children concentration statistics of the node'
) ENGINE = MergeTree()
ORDER BY (sequence)
PARTITION BY batch
TTL toDateTime(batch * 3600) + INTERVAL 24 HOUR DELETE;

CREATE TABLE IF NOT EXISTS tag_summings (
	minute DateTime64(6, 'UTC') CODEC(DoubleDelta, ZSTD(3)) COMMENT 'the minute aligned start time of the aggregation window',
	source String CODEC(ZSTD(3)) COMMENT 'the source data type of the tags, e.g. HttpTransport',
	type String CODEC(ZSTD(3)) COMMENT 'the tag dimension type, e.g. fp_tcp_client_sig',
	item String CODEC(ZSTD(3)) COMMENT 'the concrete value of the tag dimension',
	tags Array(String) COMMENT 'the deduplicated and sorted tag array of the aggregation',
	cnt UInt32 COMMENT 'the hit count of the tags, summed by SummingMergeTree'
) ENGINE = SummingMergeTree()
ORDER BY (minute, source, type, item, tags)
PARTITION BY toStartOfHour(minute)
TTL toDateTime(minute) + INTERVAL 72 HOUR DELETE;

-- 标签聚合物化视图：按分钟 + 来源 + 指纹类型 + 指纹值 + 标签组合聚合 HttpTransport 的标签命中次数
-- type/item 由 fp_tcp_client_sig、fp_tcp_server_sig 两个指纹字段展开而来：字段名为 type，字段值为 item
-- 指纹值为空的行在 ARRAY JOIN 展开前被过滤（arrayFilter 作用于元组数组）
-- 标签为空（去重后无任何标签）的行不进入聚合，避免无意义的空标签统计
CREATE MATERIALIZED VIEW IF NOT EXISTS http_transports_2_tag_summings_mv
TO tag_summings
AS
SELECT
	toStartOfMinute(timestamp) AS minute,
	'HttpTransport' AS source,
	sig.1 AS type,
	sig.2 AS item,
	arraySort(arrayDistinct(tags)) AS tags,
	toUInt32(count()) AS cnt
FROM http_transports
ARRAY JOIN arrayFilter(x -> x.2 != '', [
	('fp_tcp_client_sig', fp_tcp_client_sig),
	('fp_tcp_server_sig', fp_tcp_server_sig)
]) AS sig
WHERE length(tags) > 0
GROUP BY minute, source, type, item, tags;

