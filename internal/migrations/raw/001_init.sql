CREATE TABLE IF NOT EXISTS packet_ipv4 (
	namespace LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the namespace the packet belongs to',
	capture LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the name of the capturer',
	version LowCardinality(String) CODEC(ZSTD(3)) COMMENT 'the version of the capturer',
	session_id UUID CODEC(ZSTD(3)) COMMENT 'the session id of the packet',
	timestamp DateTime64(6, 'UTC') CODEC(DoubleDelta, ZSTD(3)) COMMENT 'the capture timestamp of the packet',
	created_at DateTime64(6, 'UTC') CODEC(DoubleDelta, ZSTD(3)) COMMENT 'the time the record is created',
	truncated Bool COMMENT 'whether the packet is truncated',
	capture_length UInt32 CODEC(ZSTD(3)) COMMENT 'the captured length of the packet in bytes',
	layer_stack String CODEC(ZSTD(3)) COMMENT 'the network layer stack of the packet',
	payload String CODEC(ZSTD(3)) COMMENT 'the payload of the packet',
	eth_dst_mac FixedString(6) COMMENT 'the destination MAC address of the ethernet frame',
	eth_src_mac FixedString(6) COMMENT 'the source MAC address of the ethernet frame',
	eth_type UInt16 CODEC(ZSTD(3)) COMMENT 'the ethernet type of the frame, identifying the upper layer protocol',
	eth_length UInt16 CODEC(ZSTD(3)) COMMENT 'the data length of the ethernet frame in bytes',
	ipv4_version UInt8 CODEC(ZSTD(3)) COMMENT 'the version of the IPv4 protocol, always 4',
	ipv4_ihl UInt8 CODEC(ZSTD(3)) COMMENT 'the internet header length of the IPv4 header in 32-bit words',
	ipv4_tos UInt8 CODEC(ZSTD(3)) COMMENT 'the type of service of the IPv4 header',
	ipv4_length UInt16 CODEC(ZSTD(3)) COMMENT 'the total length of the IPv4 packet including the header and data',
	ipv4_id UInt16 CODEC(ZSTD(3)) COMMENT 'the identification of the IPv4 packet for fragment reassembly',
	ipv4_flags UInt8 CODEC(ZSTD(3)) COMMENT 'the flags of the IPv4 header',
	ipv4_frag_offset UInt16 CODEC(ZSTD(3)) COMMENT 'the fragment offset of the IPv4 packet in 8-byte units',
	ipv4_ttl UInt8 CODEC(ZSTD(3)) COMMENT 'the time to live of the IPv4 packet',
	ipv4_ip_protocol UInt8 CODEC(ZSTD(3)) COMMENT 'the upper layer protocol of the IPv4 packet',
	ipv4_checksum UInt16 CODEC(ZSTD(3)) COMMENT 'the header checksum of the IPv4 packet',
	ipv4_src FixedString(4) COMMENT 'the source IPv4 address',
	ipv4_dst FixedString(4) COMMENT 'the destination IPv4 address',
	ipv4_options String CODEC(ZSTD(3)) COMMENT 'the options of the IPv4 header',
	ipv4_padding String CODEC(ZSTD(3)) COMMENT 'the padding bytes of the IPv4 header'
) ENGINE = MergeTree()
ORDER BY (
	namespace, 
	capture, 
	version, 
	session_id, 
	ipv4_src, 
	ipv4_dst, 
	ipv4_ip_protocol, 
	eth_src_mac, 
	eth_dst_mac, 
	eth_type, 
	timestamp
)
PARTITION BY toStartOfHour(created_at)
TTL toDateTime(created_at) + INTERVAL 24 HOUR DELETE;

