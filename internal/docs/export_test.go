// TestWriteGenerated_RejectsOutsideRoot 校验生成器拒绝写入策展目录与其他非生成路径。
func TestWriteGenerated_RejectsOutsideRoot(t *testing.T) {
	dir := t.TempDir()
	for _, output := range []string{
		"curated/tutorials/linux-dev.md",
		"../outside.md",
		"generated/../curated/x.md",
		"/abs.md",
	} {
		if err := writeGenerated(dir, output, "内容"); err == nil {
			t.Errorf("writeGenerated(%q) 未拒绝越界路径", output)
		}
	}
}

// TestWriteGenerated_RefusesNonGeneratedFile 校验目标文件缺少生成标记时拒绝覆盖，保护策展文档。
func TestWriteGenerated_RefusesNonGeneratedFile(t *testing.T) {
	dir := t.TempDir()
	target := filepath.Join(dir, "generated", "explanation", "x.md")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatalf("创建目录失败: %v", err)
	}
	if err := os.WriteFile(target, []byte("# 人工内容\n"), 0o644); err != nil {
		t.Fatalf("写入人工文件失败: %v", err)
	}
	if err := writeGenerated(dir, "generated/explanation/x.md", "新内容"); err == nil {
		t.Errorf("缺少生成标记的文件被覆盖")
	}
	data, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("读取文件失败: %v", err)
	}
	if string(data) != "# 人工内容\n" {
		t.Errorf("人工内容被修改: %q", data)
	}
}

// TestIndexDocument_LinksRelativeToDocsRoot 校验总目录位于 docs/ 下，链接均相对 docs/ 书写。
func TestIndexDocument_LinksRelativeToDocsRoot(t *testing.T) {
	index := indexDocument(nil)

	if !strings.HasPrefix(index, `<!-- Code generated by "zki create docs"`) {
		t.Errorf("总目录未以生成标记开头:\n%s", index)
	}
	for _, want := range []string{
		"# zhongkui 文档",
		"(curated/tutorials/linux-dev.md)",
		"(curated/how-to/troubleshooting.md)",
		"(generated/reference/index.md)",
		"## 按角色找文档",
	} {
		if !strings.Contains(index, want) {
			t.Errorf("总目录缺少 %q:\n%s", want, index)
		}
	}
	if strings.Contains(index, "(docs/") {
		t.Errorf("总目录不应出现 docs/ 前缀链接:\n%s", index)
	}
}

// TestNavDocument_Deterministic 校验 nav.json 连续两次生成逐字节一致，且可被解析为合法 JSON。
func TestNavDocument_Deterministic(t *testing.T) {
	first := navDocument()
	second := navDocument()
	if first != second {
		t.Errorf("nav.json 两次生成结果不一致")
	}
	var file navFile
	if err := json.Unmarshal([]byte(first), &file); err != nil {
		t.Fatalf("nav.json 不是合法 JSON: %v", err)
	}
	if file.GeneratedBy == "" || len(file.Sections) == 0 {
		t.Errorf("nav.json 缺少生成标识或分区: %+v", file)
	}
	seen := make(map[string]bool)
	for _, section := range file.Sections {
		if !Section(section.Key).Valid() {
			t.Errorf("nav.json 分区非法: %q", section.Key)
		}
		if seen[section.Key] {
			t.Errorf("nav.json 分区重复: %q", section.Key)
		}
		seen[section.Key] = true
	}
}
