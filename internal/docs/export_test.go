// TestGeneratedNarrativeDocuments_Deterministic 校验同一 projectRoot 连续两次渲染结果逐字节一致，
// 保证入 RAG 的叙述页顺序与内容幂等。
func TestGeneratedNarrativeDocuments_Deterministic(t *testing.T) {
	root := repoRoot(t)
	first, err := GeneratedNarrativeDocuments(root)
	if err != nil {
		t.Fatalf("首次 GeneratedNarrativeDocuments 返回错误: %v", err)
	}
	second, err := GeneratedNarrativeDocuments(root)
	if err != nil {
		t.Fatalf("二次 GeneratedNarrativeDocuments 返回错误: %v", err)
	}
	if !reflect.DeepEqual(first, second) {
		t.Errorf("两次渲染结果不一致: 首次 %d 条，二次 %d 条", len(first), len(second))
	}
}

// TestGeneratedNarrativeDocuments_Complete 校验叙述页文档集完整：条数等于注册表中自动生成且非手写
// 概述的条目数，且每条 Key/Title 与 Content 非空。
func TestGeneratedNarrativeDocuments_Complete(t *testing.T) {
	root := repoRoot(t)
	got, err := GeneratedNarrativeDocuments(root)
	if err != nil {
		t.Fatalf("GeneratedNarrativeDocuments 返回错误: %v", err)
	}
	want := 0
	for _, entry := range Generated() {
		if entry.NarrativeOnly && !entry.Overview {
			want++
		}
	}
	if len(got) != want {
		t.Fatalf("叙述页条数 = %d, want %d", len(got), want)
	}
	for _, doc := range got {
		if doc.Key == "" || doc.Title == "" {
			t.Errorf("叙述页 Key/Title 不能为空: %+v", doc)
		}
		if strings.TrimSpace(doc.Content) == "" {
			t.Errorf("叙述页 Content 为空: %q", doc.Key)
		}
	}
}

// TestWriteProjections_WritesWithHeader 校验投影页按稳定路径落盘，并套用统一页头与生成标记。
func TestWriteProjections_WritesWithHeader(t *testing.T) {
	dir := t.TempDir()
	p := Projection{
		Title:       "示例参考",
		Summary:     "示例摘要",
		Roles:       []Role{RoleDev},
		Scene:       "示例场景。",
		Output:      "reference/example.md",
		SourceLabel: "external spec",
		Content:     "## 小节\n\n正文",
	}

	if err := writeProjections(dir, []Projection{p}); err != nil {
		t.Fatalf("writeProjections 返回错误: %v", err)
	}

	path := filepath.Join(dir, "reference/example.md")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("读取投影页失败: %v", err)
	}
	content := string(data)

	header := `<!-- Code generated by "zki create docs" from external spec. DO NOT EDIT. -->`
	if !strings.HasPrefix(content, header) {
		t.Errorf("投影页未以生成标记开头:\n%s", content)
	}
	for _, want := range []string{
		"# 示例参考",
		"分类：参考",
		"来源：`external spec`",
		"角色：研发",
		"适用场景：示例场景。",
		"## 小节",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("投影页缺少 %q:\n%s", want, content)
		}
	}
}

// TestWriteProjections_Idempotent 校验同一投影页连续写入两次结果逐字节一致。
func TestWriteProjections_Idempotent(t *testing.T) {
	dir := t.TempDir()
	p := Projection{
		Title:       "示例参考",
		Summary:     "示例摘要",
		Roles:       []Role{RoleDev},
		Scene:       "示例场景。",
		Output:      "reference/example.md",
		SourceLabel: "external spec",
		Content:     "## 小节\n\n正文",
	}

	if err := writeProjections(dir, []Projection{p}); err != nil {
		t.Fatalf("首次 writeProjections 返回错误: %v", err)
	}
	path := filepath.Join(dir, "reference/example.md")
	first, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("首次读取投影页失败: %v", err)
	}

	if err := writeProjections(dir, []Projection{p}); err != nil {
		t.Fatalf("二次 writeProjections 返回错误: %v", err)
	}
	second, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("二次读取投影页失败: %v", err)
	}

	if string(first) != string(second) {
		t.Errorf("两次写入结果不一致:\n首次:\n%s\n二次:\n%s", first, second)
	}
}

// TestWriteProjections_Empty 校验空投影不报错且不创建任何文件。
func TestWriteProjections_Empty(t *testing.T) {
	dir := t.TempDir()
	if err := writeProjections(dir, nil); err != nil {
		t.Fatalf("writeProjections(nil) 返回错误: %v", err)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("读取目录失败: %v", err)
	}
	if len(entries) != 0 {
		t.Errorf("空投影不应创建文件，实际目录项数: %d", len(entries))
	}
}

// TestReadmeDocument_NoProjections 校验不传投影时 README 的参考分区只含统计行、无列表条目。
func TestReadmeDocument_NoProjections(t *testing.T) {
	index := readmeDocument(3, nil)

	if !strings.Contains(index, "后端全部包自动导出参考文档，共 3 篇") {
		t.Errorf("README 缺少参考档统计: %s", index)
	}

	refSection := index
	if i := strings.Index(index, "### 参考"); i >= 0 {
		refSection = index[i:]
		if j := strings.Index(refSection, "\n### "); j >= 0 {
			refSection = refSection[:j]
		}
	}
	if strings.Contains(refSection, "- [") {
		t.Errorf("不传投影时参考分区不应出现列表条目:\n%s", refSection)
	}
}

// TestReadmeDocument_LinksRelativeToRoot 校验 README 位于项目根，全部文档链接均以 docs/ 前缀书写，
// 保证相对项目根可跳转。
func TestReadmeDocument_LinksRelativeToRoot(t *testing.T) {
	index := readmeDocument(3, []Projection{{
		Title:       "示例参考",
		Summary:     "示例摘要",
		Roles:       []Role{RoleDev},
		Scene:       "示例场景。",
		Output:      "reference/example.md",
		SourceLabel: "external spec",
		Content:     "## 小节",
	}})

	if !strings.HasPrefix(index, `<!-- Code generated by "zki create docs"`) {
		t.Errorf("README 未以生成标记开头:\n%s", index)
	}
	if !strings.Contains(index, "# zhongkui") {
		t.Errorf("README 缺少封面标题:\n%s", index)
	}
	if !strings.Contains(index, "## 目录") {
		t.Errorf("README 缺少目录分区:\n%s", index)
	}
	for _, want := range []string{
		"(docs/tutorials/quick-start.md)",
		"(docs/how-to/add-datasource-plugin.md)",
		"(docs/explanation/capture-architecture.md)",
		"(docs/reference/example.md)",
		"(docs/reference/)",
	} {
		if !strings.Contains(index, want) {
			t.Errorf("README 缺少以 docs/ 前缀书写的链接 %q:\n%s", want, index)
		}
	}
}
