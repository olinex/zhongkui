// sectionItems 返回指定分区在总目录中的展示项：注册表条目按 Order 排序，参考分区追加参考索引。
func sectionItems(section Section) []indexItem {
	entries := Registry()
	sort.SliceStable(entries, func(i, j int) bool {
		if entries[i].Section != entries[j].Section {
			return entries[i].Section < entries[j].Section
		}
		return entries[i].Order < entries[j].Order
	})
	items := make([]indexItem, 0, len(entries)+1)
	for _, entry := range entries {
		if entry.Section != section {
			continue
		}
		roles := make([]string, 0, len(entry.Roles))
		for _, role := range entry.Roles {
			roles = append(roles, role.Label())
		}
		source := "生成"
		if entry.Source == SourceCurated {
			source = "策展"
		}
		items = append(items, indexItem{
			Title:    entry.Title,
			Summary:  entry.Summary,
			Output:   entry.Output,
			Category: entry.Category.Label(),
			Source:   source,
			Roles:    roles,
			Owner:    entry.Owner,
		})
	}
	if section == SectionReference {
		items = append(items, referenceItems()...)
	}
	return items
}

// indexDocument 生成 docs/index.md：文档体系唯一入口，含阅读路径、分区目录与按角色索引。
func indexDocument(refs []refPackage) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf(generatedHeaderFormat, indexSourceLabel))
	b.WriteString("\n# zhongkui 文档\n\n")
	b.WriteString("> 网络流量采集、标签计算与风险告警平台。\n\n")
	b.WriteString("本目录是文档体系的唯一入口。文档按两条轴组织：**导航分区**回答「读者现在处于哪段旅程」，")
	b.WriteString("[Diátaxis](https://diataxis.fr/) 分类回答「这一页属于哪种知识」。\n\n")
	b.WriteString("## 按目的选择阅读路径\n\n")
	b.WriteString("| 你的目的 | 建议阅读 |\n| --- | --- |\n")
	b.WriteString("| 在 Linux 上开发调试 | [Linux 开发环境部署](curated/tutorials/linux-dev.md) |\n")
	b.WriteString("| 用二进制部署到 Linux | [Linux 二进制部署](curated/tutorials/deploy-binary.md) |\n")
	b.WriteString("| 用 Docker Compose 部署 | [Docker Compose 部署](curated/tutorials/deploy-docker-compose.md) |\n")
	b.WriteString("| 部署到 Kubernetes | [Kubernetes Helm 部署](curated/tutorials/deploy-helm.md) |\n")
	b.WriteString("| 想把第一条告警跑通 | [教程：看到你的第一条风险告警](curated/tutorials/first-alert.md) |\n")
	b.WriteString("| 理解系统如何组成 | [系统总览](curated/explanation/system-overview.md) |\n")
	b.WriteString("| 查某个字段或实体 | [领域模型](curated/explanation/domain-model.md) / [术语表](curated/explanation/glossary.md) |\n")
	b.WriteString("| 查接口、表、枚举、配置 | [参考索引](generated/reference/index.md) |\n")
	b.WriteString("| 遇到故障 | [故障排查](curated/how-to/troubleshooting.md) |\n\n")

	for _, section := range Sections() {
		items := sectionItems(section)
		if len(items) == 0 {
			continue
		}
		b.WriteString("## ")
		b.WriteString(section.Label())
		b.WriteString("\n\n")
		for _, item := range items {
			b.WriteString("- [")
			b.WriteString(item.Title)
			b.WriteString("](")
			b.WriteString(item.Output)
			b.WriteString(") — ")
			b.WriteString(item.Summary)
			b.WriteString("（")
			b.WriteString(item.Category)
			b.WriteString("；")
			b.WriteString(item.Source)
			b.WriteString("）\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## 按角色找文档\n\n")
	for _, role := range Roles() {
		b.WriteString("### ")
		b.WriteString(role.Label())
		b.WriteString("\n\n")
		for _, entry := range sortedRegistry() {
			if !slices.Contains(entry.Roles, role) {
				continue
			}
			b.WriteString("- [")
			b.WriteString(entry.Title)
			b.WriteString("](")
			b.WriteString(entry.Output)
			b.WriteString(") — ")
			b.WriteString(entry.Summary)
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}

// navSection 是 nav.json 中的一个导航分区。
type navSection struct {
	// Key 分区标识。
	Key string `json:"key"`
	// Label 分区中文名。
	Label string `json:"label"`
	// Items 分区内的条目。
	Items []navItem `json:"items"`
}

// navItem 是 nav.json 中的一条文档项。
type navItem struct {
	// Title 展示标题。
	Title string `json:"title"`
	// Summary 摘要。
	Summary string `json:"summary"`
	// Output 相对 docs/ 的路径。
	Output string `json:"output"`
	// Category Diátaxis 分类。
	Category string `json:"category"`
	// Source 来源（生成或策展）。
	Source string `json:"source"`
	// Roles 角色标签。
	Roles []string `json:"roles"`
	// Owner 责任人。
	Owner string `json:"owner"`
}

// navFile 是 nav.json 的顶层结构。
type navFile struct {
	// GeneratedBy 生成来源标识。
	GeneratedBy string `json:"generatedBy"`
	// Sections 全部导航分区。
	Sections []navSection `json:"sections"`
}

// navDocument 生成 nav.json：站点侧边栏与链接检查的机器可读大纲，逐字节幂等。
func navDocument() string {
	file := navFile{GeneratedBy: indexSourceLabel, Sections: make([]navSection, 0, len(Sections()))}
	for _, section := range Sections() {
		items := sectionItems(section)
		if len(items) == 0 {
			continue
		}
		navItems := make([]navItem, 0, len(items))
		for _, item := range items {
			navItems = append(navItems, navItem{
				Title:    item.Title,
				Summary:  item.Summary,
				Output:   item.Output,
				Category: item.Category,
				Source:   item.Source,
				Roles:    item.Roles,
				Owner:    item.Owner,
			})
		}
		file.Sections = append(file.Sections, navSection{Key: string(section), Label: section.Label(), Items: navItems})
	}
	data, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		// 结构体只含字符串与切片，序列化不可能失败；返回空串会让调用方写出非法 JSON，故直接 panic。
		panic(err)
	}
	return string(data) + "\n"
}

// sortedRegistry 返回按分区与顺序排序的注册表副本，供按角色索引生成使用。
func sortedRegistry() []Entry {
	entries := Registry()
	sort.SliceStable(entries, func(i, j int) bool {
		if entries[i].Section != entries[j].Section {
			return entries[i].Section < entries[j].Section
		}
		return entries[i].Order < entries[j].Order
	})
	return entries
}

// writeGenerated 将内容幂等写入生成域：只允许 docs/index.md、docs/nav.json 与 docs/generated/ 下的路径；
// 覆盖已有文件前要求其首行带生成标记，避免路径配置错误时覆盖策展文档。
func writeGenerated(rootDir, output, content string) error {
	clean, err := generatedOutputPath(output)
	if err != nil {
		return err
	}
	target := filepath.Join(rootDir, filepath.FromSlash(clean))
	existing, readErr := os.ReadFile(target)
	// nav.json 是 JSON，无法携带生成标记；它只允许落在 docs 根，由白名单与路径校验保护。
	if clean != "nav.json" && readErr == nil && !bytes.HasPrefix(existing, []byte(generatedMarker)) {
		return errors.Newf("docs: refusing to overwrite non-generated file %q (missing generated marker)", output)
	}
	if readErr != nil && !os.IsNotExist(readErr) {
		return errors.WithStack(readErr)
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return errors.WithStack(err)
	}
	if err := os.WriteFile(target, []byte(content), 0o644); err != nil {
		return errors.WithStack(err)
	}
	return nil
}

// generatedOutputPath 校验并归一化生成输出路径：只允许 index.md、nav.json 与 generated/ 前缀。
func generatedOutputPath(output string) (string, error) {
	if output == "" {
		return "", errors.New("docs: generated output path is empty")
	}
	if path.IsAbs(output) || strings.Contains(output, "\\") {
		return "", errors.Newf("docs: generated output path must be relative: %q", output)
	}
	clean := path.Clean(output)
	if clean == "." || clean == ".." || strings.HasPrefix(clean, "../") {
		return "", errors.Newf("docs: generated output path must not escape the docs directory: %q", output)
	}
	if clean == "index.md" || clean == "nav.json" {
		return clean, nil
	}
	if strings.HasPrefix(clean, GeneratedRoot+"/") {
		return clean, nil
	}
	return "", errors.Newf("docs: generated output must be under %s/: %q", GeneratedRoot, output)
}

// pruneGenerated 删除生成域中未在本次导出集合内的陈旧文件，并自底向上清理空目录。
// 生成域由导出器独占，因此该清理不会触碰策展内容；目录清理失败（非空）时忽略。
func pruneGenerated(rootDir string, written map[string]bool) error {
	dir := filepath.Join(rootDir, GeneratedRoot)
	if _, err := os.Stat(dir); os.IsNotExist(err) {
		return nil
	}
	var dirs []string
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			dirs = append(dirs, p)
			return nil
		}
		rel, relErr := filepath.Rel(rootDir, p)
		if relErr != nil {
			return relErr
		}
		if written[path.Clean(filepath.ToSlash(rel))] {
			return nil
		}
		return os.Remove(p)
	})
	if err != nil {
		return errors.WithStack(err)
	}
	// 先深后浅删除空目录，避免父目录因仍含子目录而删除失败。
	sort.Slice(dirs, func(i, j int) bool { return len(dirs[i]) > len(dirs[j]) })
	for _, d := range dirs {
		if d == dir {
			continue
		}
		_ = os.Remove(d)
	}
	return nil
}
