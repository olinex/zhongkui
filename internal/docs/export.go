package docs

import (
	// 标准库
	"context"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	// 第三方
	"golang.org/x/tools/go/packages"

	// 项目内部

	"zhongkui.com/zhongkui/internal/pkg/errors"
)

// generatedHeaderFormat 是生成文件顶部标注的模板（含来源导入路径）。
const generatedHeaderFormat = `<!-- Code generated by "zki create docs" from %s. DO NOT EDIT. -->`

// Options 控制文档导出的行为。
type Options struct {
	// ProjectRoot 是项目根目录，用于解析包路径与输出目录。
	ProjectRoot string
	// Root 是文档输出目录（相对于 ProjectRoot），为空时使用默认值 Root。
	Root string
}

// Export 执行完整导出流程：叙述档生成、参考档生成与索引生成。
// 所有输出文件均幂等覆盖，目录按需创建。
func Export(ctx context.Context, opts Options) error {
	if err := ctx.Err(); err != nil {
		return errors.WithStack(err)
	}

	root := opts.Root
	if root == "" {
		root = Root
	}
	rootDir := filepath.Join(opts.ProjectRoot, root)
	if err := os.MkdirAll(rootDir, 0o755); err != nil {
		return errors.WithStack(err)
	}

	// 叙述档：按注册表生成教程/操作指南/解释页面
	for _, entry := range Generated() {
		if !entry.NarrativeOnly {
			continue
		}
		content, err := RenderPackage(opts.ProjectRoot, entry.Package, true)
		if err != nil {
			return err
		}
		if err := writeDoc(rootDir, entry.Output, narrativeDocument(entry, content)); err != nil {
			return err
		}
	}

	// 参考档：自动发现并导出后端全部包
	refs, err := discoverPackages(opts.ProjectRoot)
	if err != nil {
		return err
	}
	for _, ref := range refs {
		content, err := renderDir(ref.Dir, false)
		if err != nil {
			return err
		}
		// 输出路径由包实际所在目录相对项目根推导，不依赖模块导入路径，
		// 从而使构建信息缺失（如 `go run <文件>`）时导出依然正确。
		rel, err := filepath.Rel(opts.ProjectRoot, ref.Dir)
		if err != nil {
			return errors.WithStack(err)
		}
		output := filepath.Join("reference", rel+".md")
		if err := writeDoc(rootDir, output, referenceDocument(ref, content)); err != nil {
			return err
		}
	}

	// 索引档：生成 docs/README.md
	if err := writeDoc(rootDir, "README.md", indexDocument(len(refs))); err != nil {
		return err
	}
	return nil
}

// refPackage 表示参考档待导出的后端包。
type refPackage struct {
	// ImportPath 是包导入路径。
	ImportPath string
	// Name 是包名。
	Name string
	// Dir 是包所在目录。
	Dir string
}

// discoverPackages 借助 go/packages 发现 ./internal/... 与 ./cmd/... 下的全部包，
// 排除 testdata 目录、生成的 protobuf 包以及不含 Go 源码的包。
func discoverPackages(projectRoot string) ([]refPackage, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles,
		Dir:  projectRoot,
	}
	pkgs, err := packages.Load(cfg, "./internal/...", "./cmd/...")
	if err != nil {
		return nil, errors.WithStack(err)
	}

	seen := make(map[string]bool)
	refs := make([]refPackage, 0, len(pkgs))
	for _, pkg := range pkgs {
		// 跳过不含 Go 源码的目录（如仅作子包命名空间的目录），不生成占位参考页。
		if pkg.PkgPath == "" || pkg.Dir == "" || len(pkg.GoFiles) == 0 || !hasGoFiles(pkg.Dir) {
			continue
		}
		if isTestdataPath(pkg.Dir) {
			continue
		}
		if strings.Contains(pkg.PkgPath, "/internal/pkg/protobuf") {
			continue
		}
		if seen[pkg.PkgPath] {
			continue
		}
		seen[pkg.PkgPath] = true
		refs = append(refs, refPackage{ImportPath: pkg.PkgPath, Name: pkg.Name, Dir: pkg.Dir})
	}

	sort.Slice(refs, func(i, j int) bool { return refs[i].ImportPath < refs[j].ImportPath })
	return refs, nil
}

// narrativeDocument 拼接叙述档文件的完整内容（标准头部 + 渲染正文）。
func narrativeDocument(entry Entry, content string) string {
	header := fmt.Sprintf(generatedHeaderFormat, entry.Package)
	return fmt.Sprintf("%s\n# %s\n> 分类：%s · 来源：`%s` · 角色：%s · 适用场景：%s\n> %s\n\n%s\n",
		header, entry.Title, entry.Category.Label(), entry.Package, roleLabels(entry.Roles), entry.Scene, entry.Summary, strings.TrimRight(content, "\n"))
}

// roleLabels 将角色列表渲染为以 `/` 连接的中文标签串，保持 Roles 顺序。
func roleLabels(roles []Role) string {
	labels := make([]string, 0, len(roles))
	for _, role := range roles {
		labels = append(labels, role.Label())
	}
	return strings.Join(labels, "/")
}

// referenceDocument 拼接参考档文件的完整内容（标准头部 + 渲染正文）。
func referenceDocument(ref refPackage, content string) string {
	header := fmt.Sprintf(generatedHeaderFormat, ref.ImportPath)
	return fmt.Sprintf("%s\n# %s 参考\n> 分类：%s · 来源：`%s`\n\n%s\n",
		header, ref.Name, CategoryReference.Label(), ref.ImportPath, strings.TrimRight(content, "\n"))
}

// indexDocument 生成 docs/README.md 的 Diátaxis 索引内容。
func indexDocument(referenceCount int) string {
	var b strings.Builder
	b.WriteString("# zhongkui 文档\n\n")
	b.WriteString("本项目文档按 [Diátaxis](https://diataxis.fr/) 框架组织为四类：" +
		"教程（学习导向）、操作指南（任务导向）、参考（信息导向）与解释（理解导向）。\n")

	for _, category := range Categories() {
		b.WriteString("\n## ")
		b.WriteString(category.Label())
		b.WriteString("\n\n")

		if category == CategoryReference {
			b.WriteString(fmt.Sprintf("后端全部包自动导出参考文档，共 %d 篇：[reference/](reference/)\n", referenceCount))
			continue
		}

		for _, entry := range Registry() {
			if entry.Category != category {
				continue
			}
			b.WriteString("- [")
			b.WriteString(entry.Title)
			b.WriteString("](")
			b.WriteString(entry.Output)
			b.WriteString(") — ")
			b.WriteString(entry.Summary)
			b.WriteString("（角色：")
			b.WriteString(roleLabels(entry.Roles))
			b.WriteString("；")
			if entry.Package == "" {
				b.WriteString("手写")
			} else {
				b.WriteString(fmt.Sprintf("来源 `%s`", entry.Package))
			}
			b.WriteString("）\n")
		}
	}

	// 按角色找文档：汇总各角色建议阅读的条目（含手写与 kernel，不含参考）
	b.WriteString("\n## 按角色找文档\n")
	for _, role := range Roles() {
		b.WriteString("\n### ")
		b.WriteString(role.Label())
		b.WriteString("\n\n")
		for _, entry := range Registry() {
			if !slices.Contains(entry.Roles, role) {
				continue
			}
			b.WriteString("- [")
			b.WriteString(entry.Title)
			b.WriteString("](")
			b.WriteString(entry.Output)
			b.WriteString(") — ")
			b.WriteString(entry.Summary)
			b.WriteString("\n")
		}
	}
	return b.String()
}

// writeDoc 将内容幂等写入 rootDir/output，目录按需创建。
func writeDoc(rootDir, output, content string) error {
	path := filepath.Join(rootDir, output)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return errors.WithStack(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return errors.WithStack(err)
	}
	return nil
}
