// generatedHeaderFormat 是生成文件顶部标注的模板（含来源标识）。
const generatedHeaderFormat = `<!-- Code generated by "zki create docs" from %s. DO NOT EDIT. -->`

// generatedMarker 是生成文件的身份前缀：覆盖已有文件前据此确认它确实是生成物。
const generatedMarker = "<!-- Code generated by"

// indexSourceLabel 是 docs/index.md 与 nav.json 生成标记中展示的来源标识。
const indexSourceLabel = "internal/docs/registry.go"

// Projection 是由外部声明派生的文档投影页（如接口能力参考页）：正文由调用方按单一事实来源渲染，
// 导出器只负责落到生成根下的稳定路径并套用统一页头与生成标记。
type Projection struct {
	// Title 投影页标题。
	Title string
	// Summary 投影页摘要，用于索引展示。
	Summary string
	// Roles 建议阅读角色。
	Roles []Role
	// Scene 适用场景说明。
	Scene string
	// Output 相对于 docs/ 的输出路径，必须以 generated/ 开头。
	Output string
	// SourceLabel 页头「来源」展示的声明来源标识，例如 external spec。
	SourceLabel string
	// Content 已渲染正文（Markdown，不含页级标题与页头）。
	Content string
}

// Options 控制文档导出的行为。
type Options struct {
	// ProjectRoot 是项目根目录，用于解析包路径与输出目录。
	ProjectRoot string
	// Root 是文档输出目录（相对于 ProjectRoot），为空时使用默认值 Root。
	Root string
	// Projections 是需额外写出的投影页（内容由调用方按单一事实来源渲染）；为空时导出行为与不传时一致。
	Projections []Projection
	// RootCommand 是 CLI 命令树根节点；非空时额外生成 CLI 参考页。
	RootCommand *cobra.Command
}

// Export 执行完整导出流程：叙述档生成、投影页、参考档生成、参考索引、文档总目录与导航文件。
// 所有输出文件均幂等覆盖，目录按需创建；只写生成域，不触碰策展目录。
func Export(ctx context.Context, opts Options) error {
	if err := ctx.Err(); err != nil {
		return errors.WithStack(err)
	}

	root := opts.Root
	if root == "" {
		root = Root
	}
	// Root 允许是绝对路径：--check 会把生成域导出到系统临时目录后比对。
	rootDir := root
	if !filepath.IsAbs(root) {
		rootDir = filepath.Join(opts.ProjectRoot, root)
	}
	if err := os.MkdirAll(rootDir, 0o755); err != nil {
		return errors.WithStack(err)
	}
	// written 记录本次实际生成的文件，导出末尾据此清理生成域中的陈旧产物。
	written := make(map[string]bool)

	// 叙述档：按注册表生成教程/操作指南/解释页面
	for _, entry := range Generated() {
		if !entry.NarrativeOnly {
			continue
		}
		content, err := RenderPackage(opts.ProjectRoot, entry.Package, true)
		if err != nil {
			return errors.WithStack(err)
		}
		if err := writeGenerated(rootDir, entry.Output, narrativeDocument(entry, content)); err != nil {
			return errors.WithStack(err)
		}
		written[path.Clean(entry.Output)] = true
	}

	// 投影页：调用方投影 + 参考投影（接口/数据表/枚举/配置/CLI），统一落盘并套用页头。
	projections := append([]Projection{}, opts.Projections...)
	referenceProjections, err := buildReferenceProjections(opts.ProjectRoot, opts.RootCommand)
	if err != nil {
		return errors.WithStack(err)
	}
	projections = append(projections, referenceProjections...)
	if err := writeProjections(rootDir, projections); err != nil {
		return errors.WithStack(err)
	}
	for _, p := range projections {
		written[path.Clean(p.Output)] = true
	}

	// 参考档：自动发现并导出后端全部包
	refs, err := discoverPackages(opts.ProjectRoot)
	if err != nil {
		return errors.WithStack(err)
	}
	for _, ref := range refs {
		content, err := renderDir(ref.Dir, false)
		if err != nil {
			return errors.WithStack(err)
		}
		// 输出路径由包实际所在目录相对项目根推导，不依赖模块导入路径，
		// 从而使构建信息缺失（如 `go run <文件>`）时导出依然正确。
		rel, err := filepath.Rel(opts.ProjectRoot, ref.Dir)
		if err != nil {
			return errors.WithStack(err)
		}
		output := path.Join(GeneratedRoot, "reference", filepath.ToSlash(rel)+".md")
		if err := writeGenerated(rootDir, output, referenceDocument(ref, content)); err != nil {
			return errors.WithStack(err)
		}
		written[path.Clean(output)] = true
	}

	// 参考索引：为人类提供逐包入口，避免 100+ 篇参考成为孤立文件。
	referenceIndex := path.Join(GeneratedRoot, "reference", "index.md")
	if err := writeGenerated(rootDir, referenceIndex, referenceIndexDocument(refs)); err != nil {
		return errors.WithStack(err)
	}
	written[path.Clean(referenceIndex)] = true

	// 总目录与导航：docs/index.md 是文档体系唯一入口，nav.json 供站点侧边栏与链接检查消费。
	if err := writeGenerated(rootDir, "index.md", indexDocument(refs)); err != nil {
		return errors.WithStack(err)
	}
	if err := writeGenerated(rootDir, "nav.json", navDocument()); err != nil {
		return errors.WithStack(err)
	}

	// 清理生成域中的陈旧产物：生成域由本器独占，未在本次写出集合中的文件即为历史残留。
	if err := pruneGenerated(rootDir, written); err != nil {
		return errors.WithStack(err)
	}
	return nil
}

// refPackage 表示参考档待导出的后端包。
type refPackage struct {
	// ImportPath 是包导入路径。
	ImportPath string
	// Name 是包名。
	Name string
	// Dir 是包所在目录。
	Dir string
}

// discoverPackages 借助 go/packages 发现 ./internal/... 与 ./cmd/... 下的全部包，
// 排除 testdata 目录、生成的 protobuf 包以及不含 Go 源码的包。
// 包发现固定按 Linux/amd64 进行，与 docsBuildContext 保持一致，避免结果随开发机平台变化。
func discoverPackages(projectRoot string) ([]refPackage, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles,
		Dir:  projectRoot,
		Env:  packagesEnv(),
	}
	pkgs, err := packages.Load(cfg, "./internal/...", "./cmd/...")
	if err != nil {
		return nil, errors.WithStack(err)
	}

	seen := make(map[string]bool)
	refs := make([]refPackage, 0, len(pkgs))
	for _, pkg := range pkgs {
		// 跳过不含 Go 源码的目录（如仅作子包命名空间的目录），不生成占位参考页。
		if pkg.PkgPath == "" || pkg.Dir == "" || len(pkg.GoFiles) == 0 || !hasGoFiles(pkg.Dir) {
			continue
		}
		if isTestdataPath(pkg.Dir) {
			continue
		}
		if strings.Contains(pkg.PkgPath, "/internal/pkg/protobuf") {
			continue
		}
		if seen[pkg.PkgPath] {
			continue
		}
		seen[pkg.PkgPath] = true
		refs = append(refs, refPackage{ImportPath: pkg.PkgPath, Name: pkg.Name, Dir: pkg.Dir})
	}

	sort.Slice(refs, func(i, j int) bool { return refs[i].ImportPath < refs[j].ImportPath })
	return refs, nil
}

// narrativeBody 拼接叙述档正文（页头元信息行 + 摘要 + 渲染正文），不含生成标记头部。
// 落盘（narrativeDocument）与入 RAG（GeneratedNarrativeDocuments）两处共用本函数，保证零漂移。
func narrativeBody(entry Entry, content string) string {
	return fmt.Sprintf("# %s\n> 分类：%s · 来源：`%s` · 角色：%s · 适用场景：%s\n> %s\n\n%s\n",
		entry.Title, entry.Category.Label(), entry.Package, roleLabels(entry.Roles), entry.Scene, entry.Summary, strings.TrimRight(content, "\n"))
}

// narrativeDocument 拼接叙述档文件的完整内容（标准头部 + 叙述档正文）。
func narrativeDocument(entry Entry, content string) string {
	header := fmt.Sprintf(generatedHeaderFormat, entry.Package)
	return fmt.Sprintf("%s\n%s", header, narrativeBody(entry, content))
}

// NarrativeDocument 是供入 RAG 的叙述页文档：由包注释渲染而来，Content 与落盘叙述档正文同源。
type NarrativeDocument struct {
	// Key 稳定键，取条目输出路径（Entry.Output）。
	Key string
	// Title 文档标题，取条目标题（Entry.Title），作为入库与去重的稳定键。
	Title string
	// Category 条目的 Diátaxis 分类。
	Category Category
	// Roles 建议阅读角色。
	Roles []Role
	// Scene 适用场景说明。
	Scene string
	// Content 叙述档正文（narrativeBody 结果，不含 DO NOT EDIT 页头）。
	Content string
}

// GeneratedNarrativeDocuments 遍历注册表中由代码声明派生且按叙述档渲染的条目，逐条渲染包注释并
// 组装为入 RAG 的叙述页文档。正文为空（包目录不含 Go 源码）的条目直接跳过；返回顺序保持
// Registry 顺序，保证同步幂等。projectRoot 为项目根目录，用于解析导入路径对应的包目录。
func GeneratedNarrativeDocuments(projectRoot string) ([]NarrativeDocument, error) {
	out := make([]NarrativeDocument, 0, len(Generated()))
	for _, entry := range Generated() {
		if !entry.NarrativeOnly {
			continue
		}
		content, err := RenderPackage(projectRoot, entry.Package, true)
		if err != nil {
			return nil, errors.WithStack(err)
		}
		if content == "" {
			continue
		}
		out = append(out, NarrativeDocument{
			Key:      entry.Output,
			Title:    entry.Title,
			Category: entry.Category,
			Roles:    entry.Roles,
			Scene:    entry.Scene,
			Content:  narrativeBody(entry, content),
		})
	}
	return out, nil
}

// writeProjections 把投影页逐条幂等写入 rootDir，目录按需创建。
func writeProjections(rootDir string, projections []Projection) error {
	for _, p := range projections {
		if err := writeGenerated(rootDir, p.Output, projectionDocument(p)); err != nil {
			return errors.WithStack(err)
		}
	}
	return nil
}

// projectionDocument 拼接投影页文件的完整内容（标准头部 + 渲染正文），格式与叙述档一致。
func projectionDocument(p Projection) string {
	header := fmt.Sprintf(generatedHeaderFormat, p.SourceLabel)
	return fmt.Sprintf("%s\n# %s\n> 分类：%s · 来源：`%s` · 角色：%s · 适用场景：%s\n> %s\n\n%s\n",
		header, p.Title, CategoryReference.Label(), p.SourceLabel, roleLabels(p.Roles), p.Scene, p.Summary, strings.TrimRight(p.Content, "\n"))
}

// roleLabels 将角色列表渲染为以 `/` 连接的中文标签串，保持 Roles 顺序。
func roleLabels(roles []Role) string {
	labels := make([]string, 0, len(roles))
	for _, role := range roles {
		labels = append(labels, role.Label())
	}
	return strings.Join(labels, "/")
}

// referenceDocument 拼接参考档文件的完整内容（标准头部 + 渲染正文）。
func referenceDocument(ref refPackage, content string) string {
	header := fmt.Sprintf(generatedHeaderFormat, ref.ImportPath)
	return fmt.Sprintf("%s\n# %s 参考\n> 分类：%s · 来源：`%s`\n\n%s\n",
		header, ref.Name, CategoryReference.Label(), ref.ImportPath, strings.TrimRight(content, "\n"))
}

// referenceIndexDocument 生成参考索引页：按导入路径排序，逐包给出相对链接。
func referenceIndexDocument(refs []refPackage) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf(generatedHeaderFormat, "internal/docs/export.go"))
	b.WriteString("\n# 参考索引\n\n")
	b.WriteString("> 分类：参考 · 说明：后端全部包自动导出的符号参考，按导入路径排序。\n\n")
	for _, ref := range refs {
		rel := strings.TrimPrefix(ref.ImportPath, basePackagePrefix(ref.ImportPath))
		link := strings.TrimPrefix(rel, "/")
		b.WriteString("- [")
		b.WriteString(ref.Name)
		b.WriteString(" 参考](")
		b.WriteString(link)
		b.WriteString(".md) — 来源 `")
		b.WriteString(ref.ImportPath)
		b.WriteString("`\n")
	}
	return b.String()
}

// basePackagePrefix 返回导入路径的模块前缀部分，用于把导入路径转换为相对参考索引的链接。
// 项目内包统一以 zhongkuisec.com/zhongkui/ 开头；无法识别时退回包名，避免生成绝对路径链接。
func basePackagePrefix(importPath string) string {
	const modulePath = "zhongkuisec.com/zhongkui/"
	if strings.HasPrefix(importPath, modulePath) {
		return modulePath
	}
	return importPath
}

